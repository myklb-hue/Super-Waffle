//! Exports the Rust types as TypeScript, so the shell and the engine cannot
//! drift on the `.loom` schema or the block catalogue.
//!
//!     npm run gen
//!
//! The output is committed rather than gitignored: the frontend has to build
//! without a Rust toolchain present, and a committed file makes a schema change
//! visible in the diff. `npm run typecheck` fails if it is stale, because the
//! catalogue is checked against it.
use block_kinds::{BlockKind, Category, KINDS, PortDef, SettingDef, SettingKind};
use graph_format::{
    Between, Block, Defaults, Endpoint, Execution, Frame, FrameKind, Graph, Language, Overlap,
    OverlapPolicy, Port, PortType, Position, RunMode, Side, Size, Source, SourceMode, Ui, Value,
    View, Viewport, Wire,
};
use loomd::{EngineStatus, GraphSummary, OpenGraph, Reply, Request, RpcError};
use specta::Types;
use specta_typescript::Typescript;
use std::path::PathBuf;

fn main() {
    let mut types = Types::default();
    // The persisted graph.
    types.register_mut::<Graph>();
    types.register_mut::<Block>();
    types.register_mut::<Wire>();
    types.register_mut::<Endpoint>();
    types.register_mut::<Frame>();
    types.register_mut::<FrameKind>();
    types.register_mut::<Port>();
    types.register_mut::<Source>();
    types.register_mut::<Value>();
    types.register_mut::<Position>();
    types.register_mut::<Size>();
    types.register_mut::<Ui>();
    types.register_mut::<Viewport>();
    types.register_mut::<Execution>();
    types.register_mut::<Defaults>();
    types.register_mut::<Overlap>();
    types.register_mut::<Between>();
    // The grammar.
    types.register_mut::<PortType>();
    types.register_mut::<Side>();
    types.register_mut::<View>();
    types.register_mut::<RunMode>();
    types.register_mut::<OverlapPolicy>();
    types.register_mut::<SourceMode>();
    types.register_mut::<Language>();
    // The protocol between the shell and the engine.
    types.register_mut::<Request>();
    types.register_mut::<Reply>();
    types.register_mut::<EngineStatus>();
    types.register_mut::<GraphSummary>();
    types.register_mut::<OpenGraph>();
    types.register_mut::<RpcError>();
    // The catalogue.
    types.register_mut::<BlockKind>();
    types.register_mut::<Category>();
    types.register_mut::<PortDef>();
    types.register_mut::<SettingDef>();
    types.register_mut::<SettingKind>();

    let out = PathBuf::from(env!("CARGO_MANIFEST_DIR"))
        .join("../../packages/graph-core/src/generated/schema.ts");
    std::fs::create_dir_all(out.parent().unwrap()).unwrap();

    let schema = Typescript::default()
        .header(
            "// Generated by `npm run gen`.\n\
             // Do not edit by hand: Rust owns the .loom schema and the block\n\
             // catalogue, and this file is how TypeScript learns them.",
        )
        .export(&types, specta_serde::Format)
        .unwrap_or_else(|e| panic!("exporting types: {e}"));

    // Specta exports every f64 as `number | null`, because serde_json turns NaN
    // and the infinities into null. Nothing in this schema can be one:
    // `graph-format`'s reader refuses a non-finite number, so a coordinate that
    // reached TypeScript is always a number. Without this the whole of
    // `geometry.ts` would be null checks for a case that cannot happen.
    // specta-typescript 0.0.12 does not expose `enable_lossless_floats`
    // through its public API, so the flattening happens here instead.
    //
    // An *optional* float is left alone. `h?: number | null` comes from
    // `Option<f64>`, where the null is the option and not the NaN, and
    // flattening it would claim a value is always present when it is not.
    const OPTIONAL: &str = "?: number | null";
    const KEEP: &str = "\u{0}OPTIONAL-FLOAT\u{0}";
    let schema = schema.replace(OPTIONAL, KEEP);
    let schema = schema.replace(": number | null", ": number");
    let schema = schema.replace(KEEP, OPTIONAL);
    assert!(
        !schema.contains(": number | null") || schema.contains("?: number | null"),
        "a required float slipped through the flattening"
    );
    std::fs::write(&out, schema).unwrap();

    println!("wrote {}", out.display());

    // The catalogue as data, so the library panel and the tests can read it
    // without an engine running.
    let dir = out.parent().unwrap();
    let catalogue = serde_json::to_string_pretty(&KINDS).unwrap();
    let path = dir.join("catalogue.json");
    std::fs::write(&path, format!("{catalogue}\n")).unwrap();
    println!("wrote {} ({} kinds)", path.display(), KINDS.len());

    // Every ordered pair of port types and whether a wire between them is
    // legal. TypeScript has its own copy of the rule for the drag, and this is
    // what proves the two cannot drift (SPEC §4.1).
    let matrix: Vec<_> = PortType::ALL
        .iter()
        .flat_map(|from| {
            PortType::ALL.iter().map(move |to| {
                serde_json::json!({
                    "from": from.as_str(),
                    "to": to.as_str(),
                    "accepted": from.accepted_by(*to),
                })
            })
        })
        .collect();
    let path = dir.join("compatibility.json");
    std::fs::write(
        &path,
        format!("{}\n", serde_json::to_string_pretty(&matrix).unwrap()),
    )
    .unwrap();
    println!("wrote {} ({} pairs)", path.display(), matrix.len());
}
